    @Test
    public void testCall_MethodThrowsExceptionWrappedInRuntimeException() {
        ExceptionThrower et = new ExceptionThrower();
        Method m;
        try {
            m = ExceptionThrower.class.getMethod("explode");
        } catch (NoSuchMethodException e) {
            throw new RuntimeException(e);
        }
        thrown.expect(RuntimeException.class);
        thrown.expectMessage("Exception thrown inside reflectively called method");
        ReflectionUtils.call(et, m);
    }

