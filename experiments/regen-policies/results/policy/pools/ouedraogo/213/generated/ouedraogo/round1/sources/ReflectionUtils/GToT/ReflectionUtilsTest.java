    /** Simple custom annotation used for class‑ and method‑annotation tests. */
    @Retention(RetentionPolicy.RUNTIME)
    @Target({ElementType.TYPE, ElementType.METHOD})
    private @interface TestAnno {
        String value() default "";
    }

    /** Base class with an annotation. */
    @TestAnno("base")
    private static class BaseClass {
        private String privateField = "base";
        protected int protectedField = 1;
        public static final String STATIC_FIELD = "static";

        @TestAnno("baseMethod")
        public void annotatedMethod() {}
        public void overloaded(int i) {}
        public void overloaded(String s) {}
    }

    /** Sub‑class that overrides a method and adds its own annotation. */
    @TestAnno("sub")
    private static class SubClass extends BaseClass {
        private String privateField = "sub";

        @Override
        @TestAnno("subMethod")
        public void annotatedMethod() {}

        // a bridge/synthetic method generated by the compiler for the generic interface below
        public <T> T genericMethod(T t) { return t; }
    }

    /** Interface with a default method carrying an annotation. */
    private interface AnnotatedInterface {
        @TestAnno("interfaceMethod")
        default void defaultAnnotated() {}
    }

    /** Class implementing the annotated interface – used for method‑annotation hierarchy search. */
    private static class ImplementsInterface extends SubClass implements AnnotatedInterface {}

    /** Dummy annotation for testing absence. */
    @Retention(RetentionPolicy.RUNTIME)
    @Target({ElementType.TYPE, ElementType.METHOD})
    private @interface UnusedAnno {}

    /** Simple class with a no‑arg constructor and a private constructor – used for constructor tests. */
    private static class SimpleClass {
        public SimpleClass() {}
        private SimpleClass(String s) {}
    }

    /** A class that deliberately throws an exception from a method – used for call(...) exception tests. */
    private static class ExceptionThrower {
        public void explode() { throw new IllegalStateException("boom"); }
    }

    /* --------------------------------------------------------------------- */
    /*  JUnit Rules                                                          */
    /* --------------------------------------------------------------------- */

    @Rule
    public ExpectedException thrown = ExpectedException.none();

    /* --------------------------------------------------------------------- */
    /*  Step 1 – Basic functionality tests                                   */
    /* --------------------------------------------------------------------- */

    @Test
    public void testSetMethodCache_ReplacesDefaultCache() {
        Map<Object, Method> custom = new ConcurrentHashMap<>();
        ReflectionUtils.setMethodCache(custom);
        // internal state is private – we verify behaviour by putting a method and retrieving it
        Method m = ReflectionUtils.getMethod(SimpleClass.class, "toString");
        // The custom map should now contain the entry
        Assert.assertTrue(custom.containsKey(new ReflectionUtils.MethodCacheKey(SimpleClass.class, "toString")));
        // Ensure the retrieved method is the same as the reflection result
        Assert.assertEquals(m, ReflectionUtils.getMethod(SimpleClass.class, "toString"));
    }

    @Test
    public void testGetClassAnnotation_FindsDirectAndInheritedAnnotations() {
        // Direct annotation on SubClass
        TestAnno anno = ReflectionUtils.getClassAnnotation(SubClass.class, TestAnno.class);
        Assert.assertNotNull(anno);
        Assert.assertEquals("sub", anno.value());

        // Inherited annotation from BaseClass (should be found when searching BaseClass)
        TestAnno baseAnno = ReflectionUtils.getClassAnnotation(BaseClass.class, TestAnno.class);
        Assert.assertNotNull(baseAnno);
        Assert.assertEquals("base", baseAnno.value());

        // Searching for a non‑present annotation returns null
        Assert.assertNull(ReflectionUtils.getClassAnnotation(SubClass.class, UnusedAnno.class));
    }

    @Test
    public void testGetMethodAnnotation_FindsMethodAndInheritedAnnotations() throws NoSuchMethodException {
        // Direct annotation on SubClass.annotatedMethod()
        Method subMethod = SubClass.class.getDeclaredMethod("annotatedMethod");
        TestAnno anno = ReflectionUtils.getMethodAnnotation(subMethod, TestAnno.class);
        Assert.assertNotNull(anno);
        Assert.assertEquals("subMethod", anno.value());

        // Annotation defined on an interface default method should be found via hierarchy
        Method ifaceMethod = AnnotatedInterface.class.getMethod("defaultAnnotated");
        TestAnno ifaceAnno = ReflectionUtils.getMethodAnnotation(ifaceMethod, TestAnno.class);
        Assert.assertNotNull(ifaceAnno);
        Assert.assertEquals("interfaceMethod", ifaceAnno.value());

        // No annotation case
        Method noAnno = BaseClass.class.getDeclaredMethod("overloaded", int.class);
        Assert.assertNull(ReflectionUtils.getMethodAnnotation(noAnno, UnusedAnno.class));
    }

    @Test
    public void testGetField_FindsDeclaredAndInheritedFields() {
        // Field declared in SubClass
        Field f1 = ReflectionUtils.getField(SubClass.class, "privateField");
        Assert.assertNotNull(f1);
        Assert.assertEquals("privateField", f1.getName());
        Assert.assertEquals(SubClass.class, f1.getDeclaringClass());

        // Field declared in BaseClass (inherited)
        Field f2 = ReflectionUtils.getField(SubClass.class, "protectedField");
        Assert.assertNotNull(f2);
        Assert.assertEquals("protectedField", f2.getName());
        Assert.assertEquals(BaseClass.class, f2.getDeclaringClass());

        // Static field should be ignored – getField still returns it because it only matches name
        Field staticF = ReflectionUtils.getField(BaseClass.class, "STATIC_FIELD");
        Assert.assertNotNull(staticF);
        Assert.assertTrue(Modifier.isStatic(staticF.getModifiers()));
    }

    @Test
    public void testGetDeclaredFields_WithCustomPredicate() {
        Predicate<Field> onlyString = f -> f.getType() == String.class;
        List<Field> fields = ReflectionUtils.getDeclaredFields(SubClass.class, onlyString);
        // SubClass has a private String field named "privateField"
        Assert.assertEquals(1, fields.size());
        Assert.assertEquals("privateField", fields.get(0).getName());
    }

    @Test
    public void testGetAllDeclaredFields_IncludesSuperClassFields() {
        List<Field> all = ReflectionUtils.getAllDeclaredFields(SubClass.class);
        // Should contain SubClass.privateField + BaseClass.privateField + BaseClass.protectedField
        Set<String> names = new HashSet<>();
        for (Field f : all) names.add(f.getName());

        Assert.assertTrue(names.contains("privateField")); // appears twice (different declaring classes)
        Assert.assertTrue(names.contains("protectedField"));
        // The static field is filtered out by DEFAULT_FIELD_FILTER
        Assert.assertFalse(names.contains("STATIC_FIELD"));
    }

    @Test
    public void testGetAllDeclaredFieldsMap_NameCollisionResolution() {
        // Both BaseClass and SubClass declare a field called "privateField"
        Map<String, Field> map = ReflectionUtils.getAllDeclaredFieldsMap(SubClass.class);
        // Simple name maps to the field from the most‑derived class (SubClass)
        Assert.assertEquals(SubClass.class, map.get("privateField").getDeclaringClass());

        // Fully‑qualified name should reference the BaseClass field
        String fq = BaseClass.class.getName() + ".privateField";
        Assert.assertTrue(map.containsKey(fq));
        Assert.assertEquals(BaseClass.class, map.get(fq).getDeclaringClass());
    }

    @Test
    public void testCall_WithMethodObject_SuccessfulInvocation() throws Exception {
        String value = "hello";
        Method m = String.class.getMethod("toUpperCase");
        Object result = ReflectionUtils.call(value, m);
        Assert.assertEquals("HELLO", result);
    }

    @Test
    public void testCall_WithMethodName_SuccessfulInvocation() {
        String value = "world";
        Object result = ReflectionUtils.call(value, "toUpperCase");
        Assert.assertEquals("WORLD", result);
    }

    @Test
    public void testGetMethod_WithExactSignature() throws Exception {
        Method m = ReflectionUtils.getMethod(SubClass.class, "annotatedMethod");
        Assert.assertEquals("annotatedMethod", m.getName());
        // The method should be accessible even though it is declared in a subclass
        Assert.assertTrue(m.isAccessible());
    }

    @Test
    public void testGetMethod_WithArgumentCountSelection() {
        Method m = ReflectionUtils.getMethod(new SubClass(), "overloaded", 1);
        Assert.assertEquals(1, m.getParameterCount());
        // Should pick the most accessible (public) overload
        Assert.assertTrue(Modifier.isPublic(m.getModifiers()));
    }

    @Test
    public void testGetConstructor_CachesResult() {
        Constructor<?> c1 = ReflectionUtils.getConstructor(SimpleClass.class);
        Constructor<?> c2 = ReflectionUtils.getConstructor(SimpleClass.class);
        Assert.assertSame(c1, c2); // cached instance
    }

    @Test
    public void testGetAllConstructors_Ordering() {
        Constructor<?>[] ctors = ReflectionUtils.getAllConstructors(SimpleClass.class);
        // Expected order: public (no‑arg) first, then private (String)
        Assert.assertEquals(2, ctors.length);
        Assert.assertTrue(Modifier.isPublic(ctors[0].getModifiers()));
        Assert.assertTrue(Modifier.isPrivate(ctors[1].getModifiers()));
    }

    @Test
    public void testGetClassName_NullHandling() {
        Assert.assertEquals("null", ReflectionUtils.getClassName(null));
        Assert.assertEquals("java.lang.String", ReflectionUtils.getClassName("abc"));
    }

