    @Test
    public void testDeprecatedGetDeepDeclaredFields_DelegatesToNewImplementation() {
        Collection<Field> deep = ReflectionUtils.getDeepDeclaredFields(SubClass.class);
        // Should contain the same fields as getAllDeclaredFields with the legacy filter applied
        List<Field> expected = ReflectionUtils.getAllDeclaredFields(SubClass.class,
                f -> ReflectionUtils.DEFAULT_FIELD_FILTER.test(f) &&
                     !Modifier.isTransient(f.getModifiers()) &&
                     !f.isSynthetic());
        Assert.assertEquals(expected.size(), deep.size());
        Assert.assertTrue(deep.containsAll(expected));
    }

    @Test
    public void testDeprecatedGetDeepDeclaredFieldMap_DelegatesToNewImplementation() {
        Map<String, Field> deepMap = ReflectionUtils.getDeepDeclaredFieldMap(SubClass.class);
        Map<String, Field> expected = ReflectionUtils.getAllDeclaredFieldsMap(SubClass.class,
                f -> ReflectionUtils.DEFAULT_FIELD_FILTER.test(f) &&
                     !Modifier.isTransient(f.getModifiers()) &&
                     !f.isSynthetic());
        Assert.assertEquals(expected, deepMap);
    }

