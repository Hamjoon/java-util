import static org.junit.jupiter.api.Assertions.*;
import java.lang.reflect.Constructor;
import java.security.Permission;
import java.util.ArrayList;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.MethodSource;
import org.mockito.junit.jupiter.MockitoExtension;

@ExtendWith(MockitoExtension.class)
class ClassUtilities_areAllConstructorsPrivate_Test {

    /**
     * A class that defines **only** private constructors.
     */
    private static class AllPrivateConstructors {

        private AllPrivateConstructors() {
        }

        private AllPrivateConstructors(String s) {
        }
    }

    /**
     * A class that has a mix of private and public constructors.
     */
    private static class MixedConstructors {

        public MixedConstructors() {
        }

        private MixedConstructors(int i) {
        }
    }

    // intentionally empty
    private static class ImplicitPublicConstructor {
    }

    /**
     * An interface – interfaces have no constructors at all.
     */
    private interface SampleInterface {
    }

    /**
     * A class with a single private constructor (no overloads).
     */
    private static class SinglePrivateConstructor {

        private SinglePrivateConstructor() {
        }
    }

    /**
     * A class that defines **only** private constructors.
     */
    private static class PrivateOnly {

        private PrivateOnly() {
        }
    }

    /**
     * A class that defines **multiple** private constructors.
     */
    private static class MultiplePrivateConstructors {

        private MultiplePrivateConstructors() {
        }

        private MultiplePrivateConstructors(String s) {
        }
    }

    /**
     * An abstract class that defines only private constructors.
     */
    private abstract static class AbstractPrivateConstructors {

        private AbstractPrivateConstructors() {
        }

        private AbstractPrivateConstructors(int i) {
        }
    }

    /**
     * A class that mixes public and private constructors.
     */
    private static class MixedVisibility {

        public MixedVisibility() {
        }

        private MixedVisibility(int i) {
        }
    }

    // compiler supplies a public no‑arg constructor
    private static class DefaultPublic {
    }

    /**
     * A class with a single protected constructor.
     */
    private static class ProtectedConstructor {

        protected ProtectedConstructor() {
        }
    }

    // default (package) visibility constructor generated by the compiler
    static class PackagePrivateConstructor {
    }

    /**
     * Outer class with a non‑static inner class (synthetic default‑visibility constructor).
     */
    private static class Outer {

        class Inner {
        }
    }

    class Inner {
    }

    class Inner {
    }

    /**
     * A class with a single private var‑args constructor.
     */
    private static class PrivateVarargsConstructor {

        private PrivateVarargsConstructor(String... args) {
        }
    }

    /**
     * A class used to provoke a {@link SecurityException} when reflection is blocked.
     */
    private static class SecurityRestrictedClass {

        public SecurityRestrictedClass() {
        }
    }

    /**
     * Cases where **all** constructors are private → expected result {@code true}.
     */
    private static Stream<Arguments> allPrivateConstructorsProvider() {
        return Stream.of(Arguments.of(PrivateOnly.class, true, "Single private no‑arg constructor"), Arguments.of(MultiplePrivateConstructors.class, true, "Two private constructors"), Arguments.of(AbstractPrivateConstructors.class, true, "Abstract class with only private constructors"), Arguments.of(SampleEnum.class, true, "Enum constructors are implicitly private"));
    }

    /**
     * Cases where **at least one** constructor is not private → expected result {@code false}.
     */
    private static Stream<Arguments> atLeastOneNonPrivateProvider() {
        return Stream.of(Arguments.of(MixedVisibility.class, false, "Public + private constructors"), Arguments.of(DefaultPublic.class, false, "Compiler‑generated public constructor"), Arguments.of(ProtectedConstructor.class, false, "Single protected constructor"), Arguments.of(PackagePrivateConstructor.class, false, "Package‑private default constructor"), Arguments.of(ArrayList.class, false, "JDK class with public constructors"), Arguments.of(Outer.Inner.class, false, "Non‑static inner class synthetic constructor"));
    }

    /**
     * Cases with no declared constructors (interface, primitive, array) → expected {@code true}.
     */
    private static Stream<Arguments> noDeclaredConstructorsProvider() {
        return Stream.of(Arguments.of(SampleInterface.class, true, "Interface has no constructors"), Arguments.of(int.class, true, "Primitive type has no constructors"), Arguments.of(int[].class, true, "Array type has no constructors"));
    }

    /**
     * Cases that should raise an exception (null argument, security restriction).
     */
    private static Stream<Arguments> exceptionProvider() {
        return Stream.of(Arguments.of(null, NullPointerException.class, "Null argument should cause NPE"), Arguments.of(SecurityRestrictedClass.class, SecurityException.class, "SecurityManager blocks reflective access"));
    }

    @Test
    void allConstructorsArePrivate_ShouldReturnTrue() {
        assertTrue(ClassUtilities.areAllConstructorsPrivate(AllPrivateConstructors.class), "All constructors are private, expected true");
    }

    @Test
    void mixedVisibilityConstructors_ShouldReturnFalse() {
        assertFalse(ClassUtilities.areAllConstructorsPrivate(MixedConstructors.class), "Presence of a public constructor should make the result false");
    }

    @Test
    void implicitPublicConstructor_ShouldReturnFalse() {
        assertFalse(ClassUtilities.areAllConstructorsPrivate(ImplicitPublicConstructor.class), "Compiler‑generated public constructor should make the result false");
    }

    @Test
    void enumConstructorsArePrivate_ShouldReturnTrue() {
        assertTrue(ClassUtilities.areAllConstructorsPrivate(SampleEnum.class), "Enum constructors are implicitly private, expected true");
    }

    @Test
    void interfaceHasNoConstructors_ShouldReturnTrue() {
        assertTrue(ClassUtilities.areAllConstructorsPrivate(SampleInterface.class), "Interfaces have no constructors; the method should return true");
    }

    @Test
    void singlePrivateConstructor_ShouldReturnTrue() {
        assertTrue(ClassUtilities.areAllConstructorsPrivate(SinglePrivateConstructor.class), "A single private constructor should yield true");
    }

    @Test
    void nullArgument_ShouldThrowNullPointerException() {
        assertThrows(NullPointerException.class, () -> ClassUtilities.areAllConstructorsPrivate(null), "Passing null should result in NPE");
    }

    @ParameterizedTest(name = "[{index}] {2}")
    @MethodSource("allPrivateConstructorsProvider")
    void allConstructorsPrivate_ShouldReturnExpected(Class<?> clazz, boolean expected, String description) {
        assertEquals(expected, ClassUtilities.areAllConstructorsPrivate(clazz), () -> "Expected " + expected + " for class " + clazz.getName() + " – " + description);
    }

    @ParameterizedTest(name = "[{index}] {2}")
    @MethodSource("atLeastOneNonPrivateProvider")
    void atLeastOneConstructorNotPrivate_ShouldReturnFalse(Class<?> clazz, boolean expected, String description) {
        assertEquals(expected, ClassUtilities.areAllConstructorsPrivate(clazz), () -> "Expected false for class " + clazz.getName() + " – " + description);
    }

    @ParameterizedTest(name = "[{index}] {2}")
    @MethodSource("noDeclaredConstructorsProvider")
    void noDeclaredConstructors_ShouldReturnTrue(Class<?> clazz, boolean expected, String description) {
        assertEquals(expected, ClassUtilities.areAllConstructorsPrivate(clazz), () -> "Expected true for " + description);
    }

    @ParameterizedTest(name = "[{index}] {2}")
    @MethodSource("exceptionProvider")
    void exceptionalCases_ShouldThrowExpectedException(Class<?> clazz, Class<? extends Throwable> exceptionClass, String description) {
        if (exceptionClass == SecurityException.class) {
            SecurityManager original = System.getSecurityManager();
            System.setSecurityManager(new SecurityManager() {

                @Override
                public void checkPermission(Permission perm) {
                    // allow everything else
                }

                @Override
                public void checkMemberAccess(Class<?> c, int which) {
                    if (c == SecurityRestrictedClass.class) {
                        throw new SecurityException("Reflective access denied for test");
                    }
                }
            });
            try {
                assertThrows(exceptionClass, () -> ClassUtilities.areAllConstructorsPrivate(clazz), () -> "Expected SecurityException for " + clazz.getName());
            } finally {
                System.setSecurityManager(original);
            }
        } else {
            assertThrows(exceptionClass, () -> ClassUtilities.areAllConstructorsPrivate(clazz), () -> "Expected " + exceptionClass.getSimpleName() + " for " + description);
        }
    }

    @Test
    void privateVarargsConstructor_ShouldReturnTrue() {
        assertTrue(ClassUtilities.areAllConstructorsPrivate(PrivateVarargsConstructor.class), "A private var‑args constructor is still private → true");
    }
}
