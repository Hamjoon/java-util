package com.cedarsoftware.util;

import org.junit.jupiter.api.*;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.MockedStatic;
import org.mockito.junit.jupiter.MockitoExtension;
import java.time.Instant;
import static java.lang.Math.abs;
import static java.lang.System.currentTimeMillis;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;
import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.util.*;
import java.util.concurrent.*;
import java.util.stream.Collectors;
import static com.cedarsoftware.util.UniqueIdGenerator.*;

@ExtendWith(MockitoExtension.class)
class UniqueIdGenerator_getUniqueId19_Test {

    /**
     * Tolerance (in milliseconds) allowed when comparing generated dates/instants to {@code System.currentTimeMillis()}.
     */
    private static final long TOLERANCE_MS = 5L;

    private MockedStatic<System> systemMock;

    @BeforeEach
    void setupBeforeEach() {
        // By default we let System.currentTimeMillis() behave normally.
        systemMock = mockStatic(System.class, CALLS_REAL_METHODS);
        // Ensure a clean static state before each test.
        resetGeneratorState();
    }

    @AfterEach
    void teardownAfterEach() {
        // Release the static mock to avoid side‑effects on other tests.
        if (systemMock != null) {
            systemMock.close();
        }
    }

    /**
     * Reset all mutable static fields to their default values (0).
     */
    private static void resetGeneratorState() {
        try {
            setStaticField("lastTimeMillis19", 0L);
            setStaticField("count2", 0);
            setStaticField("lastGeneratedId19", 0L);
            // serverId is final – restore the original value (the class initialises it once)
            // We do not change it here; individual tests that need a custom value will
            // overwrite it explicitly.
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }

    private static void setStaticField(String name, Object value) throws Exception {
        Field f = UniqueIdGenerator.class.getDeclaredField(name);
        f.setAccessible(true);
        // Remove final modifier if present (only needed for serverId)
        if (Modifier.isFinal(f.getModifiers())) {
            Field modifiers = Field.class.getDeclaredField("modifiers");
            modifiers.setAccessible(true);
            modifiers.setInt(f, f.getModifiers() & ~Modifier.FINAL);
        }
        f.set(null, value);
    }

    private static Object getStaticField(String name) throws Exception {
        Field f = UniqueIdGenerator.class.getDeclaredField(name);
        f.setAccessible(true);
        return f.get(null);
    }

    /**
     * Extract the timestamp component from a 19‑digit ID (the high 13 digits).
     */
    private static long timestampFromId(long id) {
        return id / 1_000_000L;
    }

    /**
     * Extract the sequence component (the middle 4 digits).
     */
    private static int sequenceFromId(long id) {
        return (int) ((id % 1_000_000L) / 100L);
    }

    /**
     * Extract the serverId component (the low 2 digits).
     */
    private static int serverIdFromId(long id) {
        return (int) (id % 100L);
    }

    @Test
    void generatedIdHasNineteenDigits() {
        long id = getUniqueId19();
        assertEquals(19, String.valueOf(id).length(), "Unique ID generated by getUniqueId19() should contain exactly 19 digits");
    }

    @Test
    void idsAreMonotonicallyIncreasing() {
        long first = getUniqueId19();
        long second = getUniqueId19();
        assertTrue(second > first, "Each subsequent ID must be greater than the previous one");
    }

    @Test
    void generatesLargeBatchWithoutDuplicates() {
        // well below the 10,000 IDs per millisecond limit
        final int batchSize = 20_000;
        Set<Long> ids = new HashSet<>(batchSize);
        for (int i = 0; i < batchSize; i++) {
            ids.add(getUniqueId19());
        }
        assertEquals(batchSize, ids.size(), "All generated IDs in a batch should be unique");
    }

    @Test
    void dateConversionMatchesCurrentTime() {
        // Freeze the system clock to a known value.
        // an arbitrary epoch‑millis value
        long frozenTime = 1_600_000_000_000L;
        systemMock.when(System::currentTimeMillis).thenReturn(frozenTime);
        long id = getUniqueId19();
        Date date = getDate19(id);
        assertEquals(frozenTime, date.getTime(), "Date derived from the ID should match the mocked current time");
    }

    @Test
    void instantConversionMatchesCurrentTime() {
        // Freeze the system clock to a known value.
        long frozenTime = 1_600_000_123_456L;
        systemMock.when(System::currentTimeMillis).thenReturn(frozenTime);
        long id = getUniqueId19();
        Instant instant = getInstant19(id);
        assertEquals(frozenTime, instant.toEpochMilli(), "Instant derived from the ID should match the mocked current time");
    }

    @Test
    void toleranceWhenUsingRealClock() {
        // This test uses the real system clock; we allow a small tolerance.
        long id = getUniqueId19();
        Date date = getDate19(id);
        Instant instant = getInstant19(id);
        long now = currentTimeMillis();
        assertTrue(abs(date.getTime() - now) <= TOLERANCE_MS, "Date conversion should be within tolerance of the real clock");
        assertTrue(abs(instant.toEpochMilli() - now) <= TOLERANCE_MS, "Instant conversion should be within tolerance of the real clock");
    }

    @Test
    void clockBackwardsBranchUsesLastTimestamp() throws Exception {
        // Simulate a previous timestamp far in the future.
        long future = Long.MAX_VALUE - 1_000;
        setStaticField("lastTimeMillis19", future);
        setStaticField("count2", 0);
        setStaticField("lastGeneratedId19", 0L);
        // System clock now returns a much smaller value.
        systemMock.when(System::currentTimeMillis).thenReturn(1_000L);
        long id = getUniqueId19();
        // The timestamp part of the ID must equal the stored future value.
        assertEquals(future, timestampFromId(id), "When clock goes backwards the generator must reuse the previous timestamp");
        // ID must be greater than the previous (which was 0).
        assertTrue(id > 0, "Generated ID should be positive and greater than previous");
    }

    @Test
    void sameMillisecondNormalIncrement() throws Exception {
        long now = 1_600_000_123_456L;
        setStaticField("lastTimeMillis19", now);
        setStaticField("count2", 5);
        setStaticField("lastGeneratedId19", 0L);
        systemMock.when(System::currentTimeMillis).thenReturn(now);
        long id = getUniqueId19();
        // count should have been incremented to 6
        int countAfter = (int) getStaticField("count2");
        assertEquals(6, countAfter, "Count should be incremented within the same millisecond");
        long expected = (now * 1_000_000L) + (6L * 100L) + serverIdFromId(id);
        assertEquals(expected, id, "ID must follow the formula with the incremented count");
    }

    @Test
    void sameMillisecondCounterOverflowWaitsForNextMillis() throws Exception {
        long now = 1_600_000_123_456L;
        setStaticField("lastTimeMillis19", now);
        // after increment becomes 10_000 → overflow
        setStaticField("count2", 9_999);
        setStaticField("lastGeneratedId19", 0L);
        systemMock.when(System::currentTimeMillis).thenReturn(now);
        long id = getUniqueId19();
        // After overflow the count must be reset to 0
        int countAfter = (int) getStaticField("count2");
        assertEquals(0, countAfter, "Count must be reset after reaching the limit");
        // Timestamp must have advanced by at least one millisecond
        long ts = timestampFromId(id);
        assertTrue(ts > now, "Timestamp should be advanced to the next millisecond after overflow");
        // Verify the ID respects the new timestamp and count=0
        long expected = (ts * 1_000_000L) + (0L * 100L) + serverIdFromId(id);
        assertEquals(expected, id, "ID should be built from the new timestamp with count 0");
    }

    @Test
    void normalPathTimeAdvancedResetsCount() throws Exception {
        long old = currentTimeMillis() - 2_000L;
        setStaticField("lastTimeMillis19", old);
        setStaticField("count2", 7);
        setStaticField("lastGeneratedId19", 0L);
        // ensure it's greater
        long now = old + 2_001L;
        systemMock.when(System::currentTimeMillis).thenReturn(now);
        long id = getUniqueId19();
        // Count must be reset to 0
        int countAfter = (int) getStaticField("count2");
        assertEquals(0, countAfter, "Count should be reset when the clock moves forward");
        // Timestamp must equal the new current time
        assertEquals(now, timestampFromId(id), "Timestamp component must be the new current time");
        long expected = (now * 1_000_000L) + (0L * 100L) + serverIdFromId(id);
        assertEquals(expected, id, "ID must follow the formula with count 0");
    }

    @Test
    void generatedIdNotGreaterBranchReturnsLastPlusOne() throws Exception {
        // Force a huge previous ID
        long hugePrev = Long.MAX_VALUE - 10;
        setStaticField("lastGeneratedId19", hugePrev);
        setStaticField("lastTimeMillis19", 0L);
        setStaticField("count2", 0);
        // Mock a tiny current time so the calculated newId is far smaller
        systemMock.when(System::currentTimeMillis).thenReturn(1L);
        long id = getUniqueId19();
        assertEquals(hugePrev + 1, id, "When calculated ID is not greater, method must return lastGeneratedId19+1");
    }

    @Test
    void initialCallFreshStateProducesCorrectId() throws Exception {
        // All static fields are already reset by @BeforeEach
        long frozen = 1_600_000_123_456L;
        systemMock.when(System::currentTimeMillis).thenReturn(frozen);
        long id = getUniqueId19();
        // count should be 0, timestamp = frozen, serverId whatever the class initialised
        long expected = (frozen * 1_000_000L) + (0L * 100L) + serverIdFromId(id);
        assertEquals(expected, id, "First call must follow the base formula with count 0");
    }

    @Test
    void serverIdInfluenceIsReflectedInId() throws Exception {
        // Inject a known serverId via reflection
        // any int, not limited to 0‑99 for testing
        int injectedServerId = 12_345;
        setStaticField("serverId", injectedServerId);
        // Reset other state
        setStaticField("lastTimeMillis19", 0L);
        setStaticField("count2", 0);
        setStaticField("lastGeneratedId19", 0L);
        long frozen = 1_600_000_123_456L;
        systemMock.when(System::currentTimeMillis).thenReturn(frozen);
        long id = getUniqueId19();
        // The low‑order part of the ID must equal the injected serverId
        assertEquals(injectedServerId, serverIdFromId(id), "The serverId component of the generated ID must match the injected value");
    }

    @Test
    void concurrentCallsProduceUniqueMonotonicIds() throws Exception {
        // Clean state
        setStaticField("lastTimeMillis19", 0L);
        setStaticField("count2", 0);
        setStaticField("lastGeneratedId19", 0L);
        int threadCount = 20;
        ExecutorService exec = Executors.newFixedThreadPool(threadCount);
        ConcurrentLinkedQueue<Long> results = new ConcurrentLinkedQueue<>();
        CountDownLatch startLatch = new CountDownLatch(1);
        CountDownLatch doneLatch = new CountDownLatch(threadCount);
        for (int i = 0; i < threadCount; i++) {
            exec.submit(() -> {
                try {
                    // ensure all threads start together
                    startLatch.await();
                    results.add(getUniqueId19());
                } catch (InterruptedException ignored) {
                } finally {
                    doneLatch.countDown();
                }
            });
        }
        // fire
        startLatch.countDown();
        // wait for all
        doneLatch.await();
        exec.shutdownNow();
        List<Long> sorted = results.stream().sorted().collect(Collectors.toList());
        assertEquals(threadCount, sorted.size(), "All threads should have produced an ID");
        for (int i = 1; i < sorted.size(); i++) {
            assertTrue(sorted.get(i) > sorted.get(i - 1), "IDs must be strictly increasing when sorted");
        }
    }

    @Test
    void largeForwardJumpResetsCount() throws Exception {
        long past = currentTimeMillis() - 5_000L;
        setStaticField("lastTimeMillis19", past);
        setStaticField("count2", 42);
        setStaticField("lastGeneratedId19", 0L);
        // forward jump
        long now = past + 5_001L;
        systemMock.when(System::currentTimeMillis).thenReturn(now);
        long id = getUniqueId19();
        // Count must be reset to 0
        int countAfter = (int) getStaticField("count2");
        assertEquals(0, countAfter, "Count should be reset after a large forward time jump");
        // Timestamp component must be the new current time
        assertEquals(now, timestampFromId(id), "Timestamp must reflect the new current time after jump");
        long expected = (now * 1_000_000L) + (0L * 100L) + serverIdFromId(id);
        assertEquals(expected, id, "ID must be built with count 0 and the new timestamp");
    }

    @Test
    void countNearUpperLimitWithoutOverflow() throws Exception {
        long now = currentTimeMillis();
        setStaticField("lastTimeMillis19", now);
        setStaticField("count2", 9_998);
        setStaticField("lastGeneratedId19", 0L);
        systemMock.when(System::currentTimeMillis).thenReturn(now);
        long id = getUniqueId19();
        // Count should have incremented to 9_999 and NOT overflow
        int countAfter = (int) getStaticField("count2");
        assertEquals(9_999, countAfter, "Count should be 9,999 after increment");
        // Verify ID uses the same timestamp (no wait)
        assertEquals(now, timestampFromId(id), "Timestamp must stay the same when count has not overflowed");
        long expected = (now * 1_000_000L) + (9_999L * 100L) + serverIdFromId(id);
        assertEquals(expected, id, "ID must reflect the incremented count without waiting for next millisecond");
    }
}
