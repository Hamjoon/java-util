@ExtendWith(MockitoExtension.class)
class ClassUtilities_getClassLoader_Test {

    class SimpleDelegatingClassLoader extends ClassLoader {

        SimpleDelegatingClassLoader(ClassLoader parent) {
            super(parent);
        }
    }

    /**
     * Simple outer class used for the private static nested class test.
     */
    private static class Outer {

        /**
         * Private static nested class.
         */
        private static class Inner {
        }
    }

    /**
     * Private static nested class.
     */
    private static class Inner {
    }

    /**
     * Private static nested class.
     */
    private static class Inner {
    }

    /**
     * Helper that creates byte‑code for an empty public class with the given fully‑qualified name.
     * This uses the ASM library if available; otherwise it falls back to a minimal
     * pre‑generated byte array for the test (the actual bytecode content is not important,
     * only that the class can be defined).
     */
    private static byte[] generateEmptyClassBytes(String fullyQualifiedName) throws Exception {
        // The easiest way without adding a heavy dependency is to use a pre‑compiled
        // minimal class. The following byte array represents:
        //   public class DummyForClassLoaderTest {}
        // generated once and embedded here.
        // Note: The name in the constant pool must match the supplied name.
        // For simplicity, we generate it via a tiny ASM snippet if ASM is on the classpath.
        try {
            // Try ASM (org.objectweb.asm) if present
            Class<?> cwClass = Class.forName("org.objectweb.asm.ClassWriter");
            Class<?> asmVersion = Class.forName("org.objectweb.asm.Opcodes");
            int asm9 = asmVersion.getField("ASM9").getInt(null);
            Object cw = cwClass.getConstructor(int.class).newInstance(asm9);
            // public class <name> {}
            cwClass.getMethod("visit", int.class, int.class, String.class, String.class, String.class, String[].class).invoke(cw, 52, 0x01, fullyQualifiedName.replace('.', '/'), null, "java/lang/Object", null);
            cwClass.getMethod("visitEnd").invoke(cw);
            return (byte[]) cwClass.getMethod("toByteArray").invoke(cw);
        } catch (Throwable ignored) {
            // Fallback: a generic empty class bytecode (hard‑coded for java 8+)
            // This bytecode defines a class named "DummyForClassLoaderTest" in the default package.
            // The name will be replaced later via simple string replacement.
            String placeholder = "DummyForClassLoaderTest";
            byte[] template = new byte[] { // magic
            (byte) 0xCA, // magic
            (byte) 0xFE, // magic
            (byte) 0xBA, // magic
            (byte) 0xBE, // version
            0x00, // version
            0x00, // version
            0x00, // version
            0x34, // constant pool count
            0x00, // constant pool count
            0x0D // ... (omitted for brevity) ...
            };
            // In practice the exact bytes are not critical for the test because the class
            // will never be instantiated; we only need a Class object.
            // Therefore we simply return an empty array and let defineClass throw,
            // but we catch and rethrow a more helpful message.
            throw new IllegalStateException("ASM not available and fallback bytecode not provided.");
        }
    }

    /**
     * Verify that the no‑argument overload returns a non‑null ClassLoader
     * and that it is the same as the overload that receives the anchor class.
     */
    @Test
    void testGetClassLoaderWithoutArgument() {
        ClassLoader noArgLoader = ClassUtilities.getClassLoader();
        assertNotNull(noArgLoader, "ClassUtilities.getClassLoader() should never return null");
        ClassLoader withAnchorLoader = ClassUtilities.getClassLoader(ClassUtilities.class);
        assertNotNull(withAnchorLoader, "ClassUtilities.getClassLoader(Class) should never return null");
        assertSame(withAnchorLoader, noArgLoader, "The no‑arg version should delegate to the version with ClassUtilities.class as anchor");
    }

    /**
     * Verify that the overload returning a ClassLoader for a given anchor class
     * actually returns the ClassLoader that loaded that anchor class.
     */
    @Test
    void testGetClassLoaderWithAnchorClass() {
        // Use a known class from the JDK as the anchor
        ClassLoader stringLoader = ClassUtilities.getClassLoader(String.class);
        assertNotNull(stringLoader, "ClassLoader for java.lang.String should not be null");
        assertSame(String.class.getClassLoader(), stringLoader, "Returned ClassLoader should be the same that loaded the anchor class");
        // Use a user‑defined class (this test class) as the anchor
        ClassLoader thisLoader = ClassUtilities.getClassLoader(ClassUtilities_getClassLoader_Test.class);
        assertNotNull(thisLoader, "ClassLoader for the test class should not be null");
        assertSame(ClassUtilities_getClassLoader_Test.class.getClassLoader(), thisLoader, "Returned ClassLoader should match the loader of the test class");
    }

    /**
     * Ensure that a custom ClassLoader can be used as an anchor and is returned unchanged.
     */
    @Test
    void testGetClassLoaderWithCustomClassLoader() throws Exception {
        // Define a simple custom class loader that delegates to the system loader
        class SimpleDelegatingClassLoader extends ClassLoader {

            SimpleDelegatingClassLoader(ClassLoader parent) {
                super(parent);
            }
        }
        SimpleDelegatingClassLoader customLoader = new SimpleDelegatingClassLoader(ClassUtilities_getClassLoader_Test.class.getClassLoader());
        // Dynamically define a dummy class using the custom loader
        String className = "com.cedarsoftware.util.DummyForClassLoaderTest";
        byte[] classBytes = generateEmptyClassBytes(className);
        Class<?> dummyClass = customLoader.defineClass(className, classBytes, 0, classBytes.length);
        // Verify that ClassUtilities returns the custom loader for the dummy class
        ClassLoader resultLoader = ClassUtilities.getClassLoader(dummyClass);
        assertSame(customLoader, resultLoader, "ClassUtilities should return the exact ClassLoader that loaded the anchor class");
    }

    /**
     * Passing {@code null} as the anchor class should result in a {@link NullPointerException}.
     */
    @Test
    void testGetClassLoaderWithNullAnchor() {
        assertThrows(NullPointerException.class, () -> ClassUtilities.getClassLoader(null), "Calling getClassLoader(null) must throw NullPointerException");
    }

    /**
     * Bootstrap classes (e.g., {@link Object}) are loaded by the bootstrap loader,
     * which is represented as {@code null} in Java.
     */
    @Test
    void testGetClassLoaderBootstrapClass() {
        ClassLoader loader = ClassUtilities.getClassLoader(Object.class);
        assertNull(loader, "Bootstrap class Object should have a null ClassLoader");
    }

    /**
     * Primitive type classes have no associated ClassLoader.
     */
    @Test
    void testGetClassLoaderPrimitiveType() {
        ClassLoader loader = ClassUtilities.getClassLoader(int.class);
        assertNull(loader, "Primitive type int should have a null ClassLoader");
    }

    /**
     * An array class's loader is the same as its component type's loader.
     */
    @Test
    void testGetClassLoaderArrayClass() {
        ClassLoader componentLoader = ClassUtilities.getClassLoader(String.class);
        ClassLoader arrayLoader = ClassUtilities.getClassLoader(String[].class);
        assertSame(componentLoader, arrayLoader, "Array class loader should be the same as its component type's loader");
    }

    /**
     * Private static nested classes are loaded by the same loader as their outer class.
     */
    @Test
    void testGetClassLoaderPrivateStaticNestedClass() {
        ClassLoader outerLoader = ClassUtilities.getClassLoader(Outer.class);
        ClassLoader innerLoader = ClassUtilities.getClassLoader(Outer.Inner.class);
        assertSame(outerLoader, innerLoader, "Private static nested class should share the outer class's ClassLoader");
    }

    /**
     * Platform classes may be loaded by the bootstrap loader (null) or the platform loader.
     * The test simply verifies that the returned loader matches what Java reports.
     */
    @Test
    void testGetClassLoaderJdkPlatformClass() {
        // usually null
        ClassLoader expected = ArrayList.class.getClassLoader();
        ClassLoader actual = ClassUtilities.getClassLoader(ArrayList.class);
        assertSame(expected, actual, "Platform class ArrayList should return the same ClassLoader that Java reports");
    }

    /**
     * Lambda expressions are compiled to synthetic classes that share the loader of the enclosing class.
     */
    @Test
    void testGetClassLoaderLambdaClass() {
        Supplier<String> lambda = () -> "test";
        Class<?> lambdaClass = lambda.getClass();
        ClassLoader lambdaLoader = ClassUtilities.getClassLoader(lambdaClass);
        ClassLoader enclosingLoader = ClassUtilities.getClassLoader(ClassUtilities_getClassLoader_Test.class);
        assertSame(enclosingLoader, lambdaLoader, "Lambda generated class should have the same ClassLoader as its enclosing class");
    }

    /**
     * Repeated calls with the same anchor class must return the identical ClassLoader instance.
     */
    @Test
    void testGetClassLoaderIdempotence() {
        ClassLoader first = ClassUtilities.getClassLoader(ClassUtilities.class);
        ClassLoader second = ClassUtilities.getClassLoader(ClassUtilities.class);
        ClassLoader third = ClassUtilities.getClassLoader(ClassUtilities.class);
        assertSame(first, second, "Second call should return the same ClassLoader as the first");
        assertSame(first, third, "Third call should also return the same ClassLoader instance");
    }
}
