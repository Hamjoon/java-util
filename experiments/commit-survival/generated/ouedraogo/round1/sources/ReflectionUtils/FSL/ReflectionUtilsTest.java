    /* -------------------------------------------------------------
     *  getClassNameFromByteCode()
     * ------------------------------------------------------------- */
    @Test
    public void testGetClassNameFromByteCode() throws Exception {
        // Load the .class file of a known test class (inner class) as a resource.
        String resource = SubClass.class.getName().replace('.', '/') + ".class";
        InputStream is = ClassLoader.getSystemClassLoader().getResourceAsStream(resource);
        assertNotNull("Unable to locate class file for SubClass", is);
        byte[] bytes = is.readAllBytes();
        is.close();

        String name = ReflectionUtils.getClassNameFromByteCode(bytes);
        assertEquals(SubClass.class.getName(), name);
    }

