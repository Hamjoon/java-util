    @Test
    public void testCallByName_IllegalAccessExceptionWrapped() throws Exception {
        SubClass obj = new SubClass();
        // private method “secret” – we will call by name with 0 args; getMethod will find the public method only,
        // so it will throw IllegalArgumentException (method not found). To hit IllegalAccessException we need a
        // public method that is not accessible; not possible without a security manager. Instead we verify that
        // a missing method results in IllegalArgumentException from getMethod().
        try {
            ReflectionUtils.call(obj, "secret");
            fail("Expected IllegalArgumentException because method not found");
        } catch (IllegalArgumentException ignored) {
            // expected
        }
    }

