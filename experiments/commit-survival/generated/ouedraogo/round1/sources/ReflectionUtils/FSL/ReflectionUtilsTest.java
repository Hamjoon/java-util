    @Test
    public void testCall_IllegalAccessExceptionWrapped() throws Exception {
        SubClass obj = new SubClass();
        Method privateM = SubClass.class.getDeclaredMethod("secret"); // private, not accessible
        try {
            ReflectionUtils.call(obj, privateM);
            fail("Expected RuntimeException wrapping IllegalAccessException");
        } catch (RuntimeException e) {
            assertTrue(e.getMessage().contains("IllegalAccessException"));
            assertTrue(e.getCause() instanceof IllegalAccessException);
        }
    }

    @Test
    public void testCall_InvocationTargetExceptionWrapped() throws Exception {
        SubClass obj = new SubClass();
        Method m = SubClass.class.getMethod("throwsChecked");
        try {
            ReflectionUtils.call(obj, m);
            fail("Expected RuntimeException wrapping the original exception");
        } catch (RuntimeException e) {
            assertTrue(e.getMessage().contains("Exception thrown inside reflectively called method"));
            assertTrue(e.getCause() instanceof Exception);
            assertEquals("checked", e.getCause().getMessage());
        }
    }

