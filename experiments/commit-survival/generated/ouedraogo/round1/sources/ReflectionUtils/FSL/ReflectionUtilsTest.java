    /* -------------------------------------------------------------
     *  Helper annotation and test classes used by many test cases
     * ------------------------------------------------------------- */
    @Retention(RetentionPolicy.RUNTIME)
    @Target({ElementType.TYPE, ElementType.METHOD})
    private @interface TestAnno {
        String value();
    }

    @TestAnno("super")
    private static class SuperClass {
        public String superMethod() { return "super"; }

        @TestAnno("superMethod")
        public String annotatedSuperMethod() { return "annotatedSuper"; }

        private String privateSuperMethod() { return "privateSuper"; }
    }

    @TestAnno("iface")
    private interface TestInterface {
        @TestAnno("interfaceMethod")
        default String ifaceMethod() { return "iface"; }
    }

    private static class SubClass extends SuperClass implements TestInterface {
        public String subMethod() { return "sub"; }

        @Override
        public String ifaceMethod() { return "overriddenIface"; }

        @TestAnno("subMethod")
        public String annotatedSubMethod() { return "annotatedSub"; }

        // overloaded methods – same name, different signatures
        public String overload() { return "zero"; }
        public String overload(String s) { return "one"; }
        public String overload(int i, String s) { return "two"; }

        private String secret() { return "secret"; }

        public void throwsChecked() throws Exception { throw new Exception("checked"); }
    }

    private static class ClassWithFields {
        public int publicField;
        private String privateField;
        protected List<String> protectedField;
        static int staticField;
        transient double transientField;
        // synthetic field simulation (not generated by compiler in this test)
        Object this$synthetic;
    }

    private static class ChildWithDuplicateField extends ClassWithFields {
        private String privateField; // same name as in parent, different declaring class
    }

