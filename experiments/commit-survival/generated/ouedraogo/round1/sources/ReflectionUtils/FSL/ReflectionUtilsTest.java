    /* -------------------------------------------------------------
     *  getDeclaredFields() and getDeepDeclaredFields()
     * ------------------------------------------------------------- */
    @Test
    public void testGetDeclaredFields_ExcludesStaticAndTransient() {
        List<Field> fields = ReflectionUtils.getDeclaredFields(ClassWithFields.class);
        Set<String> names = new HashSet<>();
        for (Field f : fields) names.add(f.getName());

        // staticField and transientField must be absent
        assertFalse(names.contains("staticField"));
        assertFalse(names.contains("transientField"));
        // public, private, protected fields must be present
        assertTrue(names.contains("publicField"));
        assertTrue(names.contains("privateField"));
        assertTrue(names.contains("protectedField"));
    }

    @Test
    public void testGetDeepDeclaredFields_IncludesSuperClassFields() {
        Collection<Field> fields = ReflectionUtils.getDeepDeclaredFields(ChildWithDuplicateField.class);
        Set<String> simpleNames = new HashSet<>();
        for (Field f : fields) simpleNames.add(f.getName());

        // fields from both child and parent should be present
        assertTrue(simpleNames.contains("privateField"));
        assertTrue(simpleNames.contains("publicField"));
        // duplicate name handling is in getDeepDeclaredFieldMap, not here
    }

    @Test
    public void testGetDeepDeclaredFieldMap_DuplicateNamesHandled() {
        Map<String, Field> map = ReflectionUtils.getDeepDeclaredFieldMap(ChildWithDuplicateField.class);
        // The simple name "privateField" refers to the field from the subclass (the one encountered first)
        assertTrue(map.containsKey("privateField"));
        Field field = map.get("privateField");
        assertEquals(ChildWithDuplicateField.class, field.getDeclaringClass());

        // The parent field should be reachable via the qualified key
        String qualifiedKey = ClassWithFields.class.getName() + ".privateField";
        assertTrue(map.containsKey(qualifiedKey));
        assertEquals(ClassWithFields.class, map.get(qualifiedKey).getDeclaringClass());
    }

